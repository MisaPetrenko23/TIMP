-- ============================================================================
-- TIMP: база данных для системы аудита и анализа криптографических операций
-- СУБД: RedDatabase / Firebird 3, диалект 3, кодировка UTF8
--
-- Запуск из корня репозитория (существующий FDB-файл предварительно удалить):
--   set FIREBIRD=<путь к bin\firebird>
--   isql -q /database/create_database.sql
-- ============================================================================

SET SQL DIALECT 3;

CREATE DATABASE 'MFCApplication1\CAESARCIPHERDB.FDB'
  USER 'SYSDBA' PASSWORD 'masterkey'
  PAGE_SIZE 8192
  DEFAULT CHARACTER SET UTF8;

SET NAMES UTF8;

-- ----------------------------------------------------------------------------
-- Генераторы (sequences) для автоинкремента первичных ключей
-- ----------------------------------------------------------------------------
CREATE GENERATOR GEN_USERS_ID;
CREATE GENERATOR GEN_FILES_ID;
CREATE GENERATOR GEN_OPERATIONS_ID;
CREATE GENERATOR GEN_ANALYSIS_ID;
COMMIT WORK;

-- ----------------------------------------------------------------------------
-- Таблицы
-- ----------------------------------------------------------------------------
CREATE TABLE USERS (
    ID           INTEGER NOT NULL,
    USERNAME     VARCHAR(50) NOT NULL,
    PASSWORDHASH VARCHAR(64) NOT NULL,
    AVATAR       BLOB SUB_TYPE 0 SEGMENT SIZE 80,
    CREATEDAT    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_USERS PRIMARY KEY (ID)
);

CREATE TABLE SOURCEFILES (
    ID       INTEGER NOT NULL,
    USERID   INTEGER NOT NULL,
    FILENAME VARCHAR(255) NOT NULL,
    FILESIZE INTEGER,
    FILEHASH VARCHAR(32),
    CONSTRAINT PK_SOURCEFILES PRIMARY KEY (ID),
    CONSTRAINT FK_SOURCEFILES_USER FOREIGN KEY (USERID) REFERENCES USERS (ID)
);

CREATE TABLE ENCRYPTIONOPERATIONS (
    ID            INTEGER NOT NULL,
    FILEID        INTEGER NOT NULL,
    OPERATIONTYPE VARCHAR(20) NOT NULL,
    SHIFTKEY      INTEGER,
    STATUS        VARCHAR(20) DEFAULT 'success',
    OPERATIONDATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_ENCRYPTIONOPERATIONS PRIMARY KEY (ID),
    CONSTRAINT FK_OPERATIONS_FILE FOREIGN KEY (FILEID) REFERENCES SOURCEFILES (ID),
    CONSTRAINT CK_OPERATIONS_TYPE CHECK (OPERATIONTYPE IN ('encrypt', 'decrypt', 'crack'))
);

CREATE TABLE CRACKANALYSIS (
    ID           INTEGER NOT NULL,
    OPERATIONID  INTEGER NOT NULL,
    FOUNDSHIFT   INTEGER,
    FITNESSSCORE DOUBLE PRECISION,
    TEXTLENGTH   INTEGER,
    CONSTRAINT PK_CRACKANALYSIS PRIMARY KEY (ID),
    CONSTRAINT FK_ANALYSIS_OPERATION FOREIGN KEY (OPERATIONID) REFERENCES ENCRYPTIONOPERATIONS (ID)
);
COMMIT WORK;

-- ----------------------------------------------------------------------------
-- Триггеры BEFORE INSERT: подставляют ID из генератора, если он не задан
-- ----------------------------------------------------------------------------
SET TERM ^ ;

CREATE TRIGGER TR_USERS_BI FOR USERS
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
    IF (NEW.ID IS NULL) THEN NEW.ID = GEN_ID(GEN_USERS_ID, 1);
END ^

CREATE TRIGGER TR_FILES_BI FOR SOURCEFILES
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
    IF (NEW.ID IS NULL) THEN NEW.ID = GEN_ID(GEN_FILES_ID, 1);
END ^

CREATE TRIGGER TR_OPERATIONS_BI FOR ENCRYPTIONOPERATIONS
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
    IF (NEW.ID IS NULL) THEN NEW.ID = GEN_ID(GEN_OPERATIONS_ID, 1);
END ^

CREATE TRIGGER TR_ANALYSIS_BI FOR CRACKANALYSIS
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
    IF (NEW.ID IS NULL) THEN NEW.ID = GEN_ID(GEN_ANALYSIS_ID, 1);
END ^

SET TERM ; ^
COMMIT WORK;

